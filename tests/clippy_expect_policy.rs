//! Executable Clippy policy specimens; the helper specimens are enabled only by the policy gate.

use rstest::rstest;

/// Demonstrate the permission on a built-in test body.
#[test]
fn plain_test_can_extract_a_value() {
    let value = "7".parse::<u8>().expect("the test input is a valid byte");
    assert_eq!(value, 7, "the parsed byte must match the plain test input");
}

/// Demonstrate the same permission after the rstest macro expands.
#[rstest]
#[case("7", 7)]
fn rstest_can_extract_a_value(#[case] input: &str, #[case] expected: u8) {
    let value = input.parse::<u8>().expect("the case supplies a valid byte");
    assert_eq!(value, expected, "the parsed byte must match its case");
}

#[cfg(all(test, clippy_policy_negative))]
mod negative {
    //! Before nightly-2026-10-30 Clippy rejected these helpers; it now treats every item in a test
    //! crate as test code, so the policy gate pins that they are accepted. They stay disabled in
    //! ordinary test runs.

    use rstest::{fixture, rstest};

    /// Use `expect` in a helper under test configuration.
    fn ordinary_helper(input: &str) -> u8 {
        input
            .parse::<u8>()
            .expect("negative ordinary helper specimen")
    }

    /// Use `expect` in setup generated by a fixture macro.
    #[fixture]
    fn setup_fixture() -> u8 {
        "7".parse::<u8>().expect("negative fixture specimen")
    }

    /// Keep both arrangements reachable without executing either.
    #[rstest]
    fn exercise_helpers(setup_fixture: u8) {
        assert_eq!(
            ordinary_helper("7"),
            setup_fixture,
            "both specimens parse the same byte"
        );
    }
}
